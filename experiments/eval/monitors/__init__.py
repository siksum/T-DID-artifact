"""Comparator monitors from related work, judging the same T-DID common events.

pltl: PHOENIX-style 2-valued past-time LTL (Havelund-Rosu dynamic programming), grounded per decision.
ltl3: Bauer-Leucker-Schallhart LTL3 (top/bottom/?), Moore machine generated by LamaConv, grounded per decision.
fo:   MonPoly (MFOTL, first-order with data), 2-valued.

All three use the T-DID rule's success condition; an atom whose data is absent is false (their own
semantics). Only ltl3 can answer undetermined (?): when the decision's outcome is not observed
(decision.outcome pending or error) or the decision event is absent, the settling event has not been seen.
pltl and ltl3 are evaluated incrementally over parametric data slices (O(|phi|) per event for pltl).
"""

from __future__ import annotations

from typing import Any

JUDGES = ("pltl", "ltl3", "fo")
THREATS = ("TDID-THR-015", "TDID-THR-019")


def judge(name: str, events: list[dict], threat: str) -> list[dict]:
    """One row per decision event of `threat`, in the given (replay) order:
    {"event_id", "workflow_ref", "verdict"} with verdict in {attack, no_attack, undetermined}."""
    if threat not in THREATS:
        raise ValueError(f"unsupported threat {threat}")
    if name == "pltl":
        from experiments.eval.monitors import pltl as m
    elif name == "ltl3":
        from experiments.eval.monitors import ltl3 as m
    elif name == "fo":
        from experiments.eval.monitors import fo as m
    else:
        raise ValueError(f"unknown judge {name}")
    rows: list[dict[str, Any]] = m.judge(list(events), threat)
    return rows
